#!/usr/bin/env python3
"""Render the TFT wordmarks; requires Pillow and GNU FreeFont 20120503.

See assets/tft/README.md for the source fonts and regeneration command.
"""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
BACKGROUND = (255, 255, 255)
FLOW_COLOR = (7, 59, 102)
IO_COLOR = (0, 174, 239)
SCALE = 8
# Match the previous GFX wordmark bounds (flow width + .io width).
VARIANTS = (
    ("Splash", "FreeSans.ttf", 18, 92, 26),
    ("Header", "FreeSansBold.ttf", 12, 72, 18),
)


def render(font_path: Path, points: int, width: int, height: int) -> Image.Image:
    # Adafruit's font converter uses 141 DPI. Render larger, then downsample
    # the complete wordmark so both colours share the same baseline and spacing.
    font = ImageFont.truetype(str(font_path), round(points * 141 / 72 * SCALE))
    bounds = font.getbbox("flow.io")
    size = (bounds[2] - bounds[0], bounds[3] - bounds[1])
    image = Image.new("RGB", size, BACKGROUND)
    draw = ImageDraw.Draw(image)
    origin = (-bounds[0], -bounds[1])
    draw.text(origin, "flow", font=font, fill=FLOW_COLOR)
    draw.text((origin[0] + font.getlength("flow"), origin[1]), ".io", font=font, fill=IO_COLOR)
    return image.resize((width, height), Image.Resampling.LANCZOS)


def rgb565(image: Image.Image) -> list[int]:
    return [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            for r, g, b in image.get_flattened_data()]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font-dir", required=True, type=Path)
    args = parser.parse_args()
    output = ROOT / "assets/tft"
    output.mkdir(parents=True, exist_ok=True)
    lines = ["// Generated by scripts/generate_tft_wordmarks.py; do not edit.",
             "// RGB565, anti-aliased against the white TFT header background.",
             "#pragma once", "#include <Arduino.h>", ""]
    for name, filename, points, width, height in VARIANTS:
        image = render(args.font_dir / filename, points, width, height)
        pixels = rgb565(image)
        # Preview the quantized colours actually stored in firmware.
        image.putdata([(((p >> 11) & 31) * 255 // 31,
                        ((p >> 5) & 63) * 255 // 63,
                        (p & 31) * 255 // 31) for p in pixels])
        image.save(output / f"flowio-wordmark-{name.lower()}.png")
        prefix = f"kFlowIoWordmark{name}"
        lines.extend([f"static constexpr int16_t {prefix}Width = {width};",
                      f"static constexpr int16_t {prefix}Height = {height};",
                      f"static const uint16_t {prefix}Bitmap[] PROGMEM = {{"])
        for start in range(0, len(pixels), 12):
            lines.append("    " + ", ".join(f"0x{p:04X}" for p in pixels[start:start + 12]) + ",")
        lines.extend(["};", f"static_assert(sizeof({prefix}Bitmap) / sizeof(uint16_t) ==",
                      f"              {prefix}Width * {prefix}Height, \"Invalid wordmark dimensions\");", ""])
    (ROOT / "src/Modules/TFTModuleS3/FlowIoWordmarkBitmaps.h").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
